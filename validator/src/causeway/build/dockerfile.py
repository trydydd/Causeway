"""Render a Dockerfile from a validated manifest.

The platform owns this recipe — the user never writes or sees a Dockerfile in
their project (D3). This module is a pure function of the manifest plus one
fact about the project (whether a dependency file is present), so it is fully
unit-testable without a container runtime.

Adding a runtime: extend the ``runtime`` enum in the canonical schema first,
then add its base image here and, if it is a new language family, a branch in
``render_dockerfile`` and an entry in ``DEPENDENCY_FILE``.
"""
from __future__ import annotations

import json

# Golden base images, keyed by the manifest ``runtime`` enum. Pinned by tag for
# the local POC; a platform-maintained registry with digest pinning is the
# graduation step (D35). Keep this map in lockstep with the schema's runtime enum.
BASE_IMAGES: dict[str, str] = {
    "python3.11": "python:3.11-slim",
    "python3.12": "python:3.12-slim",
    "node20": "node:20-slim",
    "node22": "node:22-slim",
}

# The dependency manifest the platform installs from, per language family. Its
# presence in the project toggles the install step in the rendered Dockerfile.
DEPENDENCY_FILE: dict[str, str] = {
    "python": "requirements.txt",
    "node": "package.json",
}

# Files that must never enter the build context — either infra the platform
# owns, local-only secrets, or heavy/derived dirs. Mirrored as a .dockerignore
# in the ephemeral context (runner.py) for belt-and-suspenders.
CONTEXT_EXCLUDES: tuple[str, ...] = (
    ".git",
    ".gitignore",
    ".github",
    "node_modules",
    "__pycache__",
    "*.pyc",
    ".venv",
    "venv",
    ".causeway.env",
    ".env",
    "Dockerfile",
    ".dockerignore",
)


def runtime_family(runtime: str) -> str:
    """Map a ``runtime`` enum value to its language family ('python' | 'node')."""
    if runtime.startswith("python"):
        return "python"
    if runtime.startswith("node"):
        return "node"
    # Unreachable for a schema-valid manifest; guards against an enum/base-image
    # map drift where someone adds a runtime to the schema but not here.
    raise ValueError(
        f"Unknown runtime {runtime!r}. Known runtimes: {', '.join(BASE_IMAGES)}."
    )


def dependency_file(runtime: str) -> str:
    """The dependency manifest filename the platform installs for this runtime."""
    return DEPENDENCY_FILE[runtime_family(runtime)]


def render_dockerfile(manifest: dict, *, has_deps: bool) -> str:
    """Render the Dockerfile text for a validated manifest.

    ``has_deps`` is whether the project contains the dependency file for this
    runtime's family (requirements.txt / package.json). It is passed in rather
    than read here so the function stays pure and golden-testable.
    """
    runtime = manifest["runtime"]
    family = runtime_family(runtime)
    base = BASE_IMAGES[runtime]
    name = manifest.get("name", "app")
    port = manifest["port"]
    entrypoint = manifest["entrypoint"]

    lines: list[str] = [
        "# syntax=docker/dockerfile:1",
        "# Generated by Causeway from causeway.yaml. The platform owns this file —",
        "# do not edit or commit it. Change behaviour via the manifest, not here.",
        f"FROM {base}",
        'LABEL causeway.managed="true"',
        f'LABEL causeway.name="{name}"',
        "WORKDIR /app",
    ]

    if family == "python":
        # Unbuffered stdout so `cwy up` log streaming is live, not block-buffered.
        lines.append("ENV PYTHONUNBUFFERED=1")
        if has_deps:
            # Install deps in their own layer (before COPY . .) so edits to app
            # code don't bust the dependency cache.
            lines.append("COPY requirements.txt ./")
            lines.append("RUN pip install --no-cache-dir -r requirements.txt")
    elif family == "node":
        if has_deps:
            lines.append("COPY package.json ./")
            lines.append("RUN npm install --omit=dev")

    lines.append("COPY . ./")
    lines.append(f"EXPOSE {port}")
    # JSON exec form wrapping a shell, so manifest entrypoints with args
    # ('uvicorn main:app --port ...', 'npm start') run verbatim while avoiding
    # buildkit's shell-form CMD signal warning. The entrypoint is the user's
    # declared start command (schema-validated, min length 1).
    lines.append(f'CMD ["sh", "-c", {json.dumps(entrypoint)}]')

    return "\n".join(lines) + "\n"
